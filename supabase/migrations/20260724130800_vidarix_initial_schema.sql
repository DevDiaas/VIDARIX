-- 4. AUTOMATIC PROFILE CREATION TRIGGER
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  raw_user_name TEXT;
  clean_username TEXT;
BEGIN
  raw_user_name := COALESCE(
    NEW.raw_user_meta_data->>'full_name',
    NEW.raw_user_meta_data->>'name',
    SPLIT_PART(NEW.email, '@', 1),
    'Cinéfilo VIDARIX'
  );

  clean_username := COALESCE(
    NEW.raw_user_meta_data->>'username',
    LOWER(REGEXP_REPLACE(SPLIT_PART(NEW.email, '@', 1), '[^a-zA-Z0-9._]', '', 'g'))
  );

  IF clean_username = '' OR clean_username IS NULL THEN
    clean_username := 'user_' || SUBSTRING(NEW.id::text FROM 1 FOR 8);
  END IF;

  INSERT INTO public.profiles (
    id,
    full_name,
    display_name,
    username,
    avatar_url,
    country,
    language,
    created_at,
    updated_at
  )
  VALUES (
    NEW.id,
    raw_user_name,
    COALESCE(NEW.raw_user_meta_data->>'display_name', SPLIT_PART(raw_user_name, ' ', 1), raw_user_name),
    clean_username,
    NEW.raw_user_meta_data->>'avatar_url',
    'BR',
    'pt-BR',
    NOW(),
    NOW()
  )
  ON CONFLICT (id) DO NOTHING;

  INSERT INTO public.user_preferences (user_id)
  VALUES (NEW.id)
  ON CONFLICT (user_id) DO NOTHING;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

